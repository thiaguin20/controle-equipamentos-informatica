const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

test('fluxos de retirada, devolução, estoque e cadastro do Admin', () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'controle-equipamentos-test-'));
  process.env.EQUIPMENT_TEST_DATA_DIR = directory;
  const db = require('../electron/database');
  try {
    const initial = db.admin();
    assert.equal(initial.teachers.filter(item=>item.name==='Professor 1').length,1);
    assert.equal(initial.teachers.filter(item=>item.name==='Professor 35').length,1);
    const teacherId = initial.teachers[0].id;
    const locationId = initial.locations[0].id;
    db.saveEntity({type:'equipment',item:{name:'Mouse',icon:'🖱️',total:12,quantity_controlled:1,active:1,is_cart:0}});
    let mouse = db.admin().equipment.find(item=>item.name==='Mouse');
    assert.equal(mouse.total,12);
    assert.equal(mouse.available,12);
    db.createWithdrawal({teacherId,equipmentId:mouse.id,quantity:4,locationId});
    mouse = db.admin().equipment.find(item=>item.id===mouse.id);
    assert.equal(mouse.available,8);
    db.saveEntity({type:'equipment',item:{...mouse,total:15}});
    mouse = db.admin().equipment.find(item=>item.id===mouse.id);
    assert.equal(mouse.total,15);
    assert.equal(mouse.available,11);
    assert.throws(()=>db.saveEntity({type:'equipment',item:{...mouse,total:3}}),/em uso/);
    db.saveEntity({type:'location',item:{name:'Sala cadastrada por engano',active:1}});
    const unusedRoom=db.admin().locations.find(item=>item.name==='Sala cadastrada por engano');
    db.deleteEntity({type:'location',id:unusedRoom.id});
    assert.equal(db.admin().locations.some(item=>item.id===unusedRoom.id),false);
    assert.throws(()=>db.deleteEntity({type:'location',id:locationId}),/retirada/);
    assert.throws(()=>db.deleteEntity({type:'equipment',id:mouse.id}),/retirada/);
    const notebook=db.admin().equipment.find(item=>item.name==='Notebook');
    const withdrawalId=db.createWithdrawal({teacherId,equipmentId:notebook.id,quantity:20,locationId});
    assert.equal(db.catalog().equipment.find(item=>item.id===notebook.id).available,5);
    assert.equal(db.dashboard().find(item=>item.id===withdrawalId).quantity,20);
    assert.throws(()=>db.createWithdrawal({teacherId,equipmentId:notebook.id,quantity:10,locationId}),/5 disponíveis/);
    db.updateWithdrawal({id:withdrawalId,forceReturn:true});
    assert.equal(db.catalog().equipment.find(item=>item.id===notebook.id).available,25);
    assert.equal(db.dashboard().some(item=>item.id===withdrawalId),false);
    const cart=db.admin().equipment.find(item=>item.is_cart===1);
    db.createWithdrawal({teacherId,equipmentId:cart.id,quantity:1,locationId});
    assert.equal(db.catalog().equipment.find(item=>item.id===cart.id).available,0);
    assert.throws(()=>db.createWithdrawal({teacherId,equipmentId:cart.id,quantity:1,locationId}),/já está em uso/);
    db.saveEntity({type:'teacher',item:{...initial.teachers[0],active:0}});
    assert.equal(db.catalog().teachers.some(item=>item.id===teacherId),false);
    assert.equal(db.dashboard().some(item=>item.teacher_id===teacherId),true);
    const unusualId=db.createWithdrawal({teacherName:'Professora Nova',equipmentName:'Adaptador especial',quantity:2,locationName:'Sala extra'});
    assert.equal(db.dashboard().find(item=>item.id===unusualId).teacher,'Professora Nova');
    assert.equal(db.dashboard().find(item=>item.id===unusualId).equipment,'Adaptador especial');
    assert.equal(db.admin().pendingTeachers.length,1);
    assert.equal(db.admin().pendingEquipment.length,1);
    assert.equal(db.admin().pendingLocations.length,1);
    assert.equal(db.catalog().teachers.some(item=>item.name==='Professora Nova'),false);
    assert.equal(db.catalog().equipment.some(item=>item.name==='Adaptador especial'),false);
    const pendingTeacher=db.admin().pendingTeachers[0];
    const pendingEquipment=db.admin().pendingEquipment[0];
    const pendingLocation=db.admin().pendingLocations[0];
    db.createWithdrawal({teacherName:'Professora Nova',equipmentName:'Adaptador especial',quantity:1,locationName:'Sala extra'});
    assert.equal(db.admin().pendingTeachers.length,1);
    assert.equal(db.admin().pendingEquipment.length,1);
    assert.throws(()=>db.saveEntity({type:'equipment',item:{...pendingEquipment,total:2,active:1}}),/em uso/);
    db.saveEntity({type:'teacher',item:{...pendingTeacher,active:1}});
    db.saveEntity({type:'equipment',item:{...pendingEquipment,total:3,active:1}});
    db.saveEntity({type:'location',item:{...pendingLocation,active:1}});
    assert.equal(db.admin().pendingTeachers.length,0);
    assert.equal(db.admin().pendingEquipment.length,0);
    assert.equal(db.admin().pendingLocations.length,0);
    assert.equal(db.catalog().equipment.find(item=>item.name==='Adaptador especial').available,0);
    assert.throws(()=>db.createWithdrawal({teacherId:pendingTeacher.id,equipmentId:pendingEquipment.id,quantity:1,locationId}),/0 disponíveis/);
    db.updateWithdrawal({id:unusualId,forceReturn:true});
    assert.equal(db.catalog().equipment.find(item=>item.name==='Adaptador especial').available,2);
  } finally {
    db.getDb().close();
    fs.rmSync(directory,{recursive:true,force:true});
    delete process.env.EQUIPMENT_TEST_DATA_DIR;
  }
});
